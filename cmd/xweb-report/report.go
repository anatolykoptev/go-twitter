// Verdicts.
const (
	verdictSame     = "same-shape"
	verdictNew      = "new-shape"
	verdictNotFound = "not-found-in-x-web"
	verdictUnknown  = "undetermined"
)

// row is the comparison of one go-twitter operation against the crawl.
type row struct {
	spec     opSpec
	legacyID string
	x        *gqlextract.Op // nil when not found
	alts     []string       // other candidate names that were also found
	verdict  string
	reason   string
}

// compare builds the row for spec against the extracted x-web operations.
func compare(spec opSpec, legacyID string, byName map[string]gqlextract.Op) row {
	r := row{spec: spec, legacyID: legacyID}
	for _, name := range spec.XWeb {
		op, ok := byName[name]
		switch {
		case !ok:
		case r.x == nil:
			op := op
			r.x = &op
		default:
			r.alts = append(r.alts, name)
		}
	}
	if r.x == nil {
		r.verdict, r.reason = verdictNotFound, "no artifact named "+strings.Join(codeAll(spec.XWeb), " / ")
		return r
	}
	r.verdict, r.reason = shapeVerdict(spec.LegacyRoot, r.x.ResponseRoot)
	return r
}

// shapeVerdict decides, from the artifact alone, whether the response envelope
// the legacy parser reads is still what the operation returns.
//
//   - A `__…` segment in the x-web root is the client's own normalised timeline
//     connection (the artifact imports timeline_normalization / create-urt): the
//     wire timeline is not the legacy URT, so it is new-shape whatever the root
//     says (this is the shape devicefollow.go's xwebTimeline parser already
//     handles: entry_id, content.content, details.full_text, created_at_ms).
//   - Otherwise the legacy root path must be a prefix-compatible walk of the
//     x-web chain; a `{a,b}` sibling set matches when it contains the legacy
//     segment.
//
// Equal roots do NOT prove the inner objects (tweet/user result fields) are
// unchanged; the artifact's fragments name them but the report does not diff them.
func shapeVerdict(legacyRoot, xRoot string) (verdict, reason string) {
	if xRoot == "" {
		return verdictUnknown, "the artifact's response selection is not in the crawled chunk"
	}
	xs := strings.Split(xRoot, ".")
	for _, s := range xs {
		if strings.HasPrefix(s, "__") {
			return verdictNew, fmt.Sprintf("x-web `%s` ends in the client-normalised URT connection `%s` (legacy `%s`)", xRoot, s, legacyRoot)
		}
	}
	if legacyRoot == "" {
		return verdictUnknown, "no legacy call site to compare against"
	}
	ls := strings.Split(legacyRoot, ".")
	matched := 0
	for i := 0; i < len(ls) && i < len(xs); i++ {
		if strings.HasPrefix(xs[i], "{") {
			set := strings.Split(strings.Trim(xs[i], "{}"), ",")
			if !contains(set, ls[i]) {
				return verdictNew, fmt.Sprintf("legacy `%s` not among x-web `%s` (root `%s`)", ls[i], xs[i], xRoot)
			}
			matched++
			break
		}
		if xs[i] != ls[i] {
			return verdictNew, fmt.Sprintf("root `%s` -> `%s`", legacyRoot, xRoot)
		}
		matched++
	}
	if matched == 0 {
		return verdictNew, fmt.Sprintf("root `%s` -> `%s`", legacyRoot, xRoot)
	}
	return verdictSame, fmt.Sprintf("root `%s` matches x-web `%s`; inner objects not diffed", legacyRoot, xRoot)
}

func contains(s []string, v string) bool {
	for _, e := range s {
		if e == v {
			return true
		}
	}
	return false
}

func codeAll(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = "`" + s + "`"
	}
	return out
}

// diffVars returns the variables only x-web declares and the ones only legacy sends.
func diffVars(legacy, xweb []string) (added, dropped []string) {
	for _, v := range xweb {
		if !contains(legacy, v) {
			added = append(added, v)
		}
	}
	for _, v := range legacy {
		if !contains(xweb, v) {
			dropped = append(dropped, v)
		}
	}
	return added, dropped
}

// build compares every spec; rows keep the spec order.
func build(legacyIDs map[string]string, ops []gqlextract.Op) []row {
	byName := make(map[string]gqlextract.Op, len(ops))
	for _, o := range ops {
		byName[o.Name] = o
	}
	rows := make([]row, 0, len(specs))
	for _, s := range specs {
		rows = append(rows, compare(s, legacyIDs[s.Legacy], byName))
	}
	return rows
}

// meta describes the crawl for the report header.
type meta struct {
	Entry        string
	Fetched      int
	Failed       int
	Capped       bool
	Artifacts    int
	Queries      int
	Mutations    int
	Conflicts    map[string][]string
	GeneratedFor string // optional date stamp
}

func render(rows []row, m meta) string {
	var b strings.Builder
	b.WriteString("# x-web migration inventory\n\n")
	b.WriteString("Generated by `go run ./cmd/xweb-report` (issue #119, phase 1). Do not edit by hand.\n\n")
	if m.GeneratedFor != "" {
		fmt.Fprintf(&b, "Crawl date: %s.\n\n", m.GeneratedFor)
	}
	fmt.Fprintf(&b, "Source: the public logged-out shell, entry script `%s`, followed through its chunk graph "+
		"(%d chunks fetched, %d unreachable literals skipped, capped: %v). No cookies, no account, no API call. "+
		"Parsed %d Relay artifacts (%d queries, %d mutations).\n\n",
		m.Entry, m.Fetched, m.Failed, m.Capped, m.Artifacts, m.Queries, m.Mutations)
	b.WriteString("The logged-out build is one audience's view: the authenticated build can carry different artifacts and ids, " +
		"so a Phase 2 switch must re-confirm each id with a live probe before use.\n\n")

	b.WriteString("## Verdicts\n\n")
	b.WriteString("- **same-shape**: the response root the go-twitter parser reads is unchanged. Inner tweet/user objects are not diffed.\n")
	b.WriteString("- **new-shape**: the root moved, or the artifact normalises the timeline through the client's own URT layer " +
		"(entries arrive as `entry_id` / `content.content` / `details.full_text` / `created_at_ms`, see `xwebTimeline` in `devicefollow.go`), " +
		"so the legacy timeline parser cannot read it.\n")
	b.WriteString("- **not-found-in-x-web**: no artifact under any candidate name in the crawled graph.\n")
	b.WriteString("- **undetermined**: the artifact was found but its response selection could not be read from the chunk.\n\n")

	b.WriteString("## Operation inventory\n\n")
	b.WriteString("| Operation | Legacy id | x-web operation | x-web id | Provided vars | Verdict | Parser |\n|---|---|---|---|---|---|---|\n")
	for _, r := range rows {
		xn, xid, pv := "-", "-", "-"
		if r.x != nil {
			xn, xid, pv = "`"+r.x.Name+"`", "`"+r.x.ID+"`", fmt.Sprint(len(r.x.Providers))
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s | %s | `%s` |\n", r.spec.Legacy, r.legacyID, xn, xid, pv, r.verdict, r.spec.Parser)
	}

	b.WriteString("\n## Findings\n\n")
	b.WriteString(findings(rows))

	b.WriteString("\n## Per-operation detail\n")
	for _, r := range rows {
		b.WriteString(detail(r))
	}
	if len(m.Conflicts) > 0 {
		b.WriteString("\n## Operations with more than one id in the crawl\n\n")
		names := make([]string, 0, len(m.Conflicts))
		for n := range m.Conflicts {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			fmt.Fprintf(&b, "- `%s`: extra ids %s (the first was kept)\n", n, strings.Join(codeAll(m.Conflicts[n]), ", "))
		}
	}
	b.WriteString("\n## Reproducing, and the runtime flag\n\n")
	b.WriteString("`go run ./cmd/xweb-report -cache <dir> -out docs/xweb-migration.md -date <YYYY-MM-DD>` re-crawls (the cache keeps re-runs off the network; " +
		"`-offline` forbids it). The run is a few thousand polite requests for static JavaScript, with four workers and a pause between requests.\n\n")
	b.WriteString("The runtime queryId refresher can read the same graph: set `TWITTER_QID_XWEB=on` (default off). It then updates only the operations " +
		"go-twitter already issues against x-web (currently `tweetNotificationsQuery`); every other operation keeps its legacy id, because an x-web id " +
		"is a different persisted call (other variables, other response shape).\n")
	return b.String()
}

func findings(rows []row) string {
	var b strings.Builder
	counts := map[string]int{}
	for _, r := range rows {
		counts[r.verdict]++
	}
	fmt.Fprintf(&b, "- %d operations: %d new-shape, %d same-shape, %d not-found-in-x-web, %d undetermined.\n",
		len(rows), counts[verdictNew], counts[verdictSame], counts[verdictNotFound], counts[verdictUnknown])
	for _, r := range rows {
		if r.x == nil || r.x.Name != r.spec.Legacy || r.legacyID == r.x.ID {
			continue
		}
		if _, native := xwebnative.Ops()[r.spec.Legacy]; native {
			fmt.Fprintf(&b, "- `%s` already runs on x-web, but the committed id `%s` differs from the artifact id `%s`: "+
				"the persisted query changed since it was hand-extracted, or the audiences differ. A live probe must decide which one answers.\n",
				r.spec.Legacy, r.legacyID, r.x.ID)
			continue
		}
		fmt.Fprintf(&b, "- `%s` exists on both stacks under the same name with different ids (legacy `%s`, x-web `%s`); per #119 the legacy id still answers (not re-verified here), so the ids differ per stack rather than by rotation.\n",
			r.spec.Legacy, r.legacyID, r.x.ID)
	}
	lo, hi := providerRange(rows)
	fmt.Fprintf(&b, "- Mapped x-web operations declare between %d and %d `__relay_internal__pv__*` provided variables "+
		"(column above); the request must send them as plain variables.\n", lo, hi)
	b.WriteString("- x-web artifacts declare no feature switches: the request carries `variables` only (as `tweetNotificationsURL` already does).\n")
	return b.String()
}

func detail(r row) string {
	var b strings.Builder
	fmt.Fprintf(&b, "\n### %s\n\n- verdict: **%s** — %s\n", r.spec.Legacy, r.verdict, r.reason)
	if r.x == nil {
		if r.spec.Note != "" {
			fmt.Fprintf(&b, "- note: %s\n", r.spec.Note)
		}
		return b.String()
	}
	fmt.Fprintf(&b, "- x-web operation: `%s` (%s)\n", r.x.Name, r.x.Kind)
	if len(r.alts) > 0 {
		fmt.Fprintf(&b, "- also present: %s\n", strings.Join(codeAll(r.alts), ", "))
	}
	added, dropped := diffVars(r.spec.LegacyVars, r.x.Variables)
	fmt.Fprintf(&b, "- x-web variables: %s\n", listOrNone(r.x.Variables))
	fmt.Fprintf(&b, "- only in x-web: %s; only in legacy: %s\n", listOrNone(added), listOrNone(dropped))
	fmt.Fprintf(&b, "- provided variables: %d; features: none declared\n", len(r.x.Providers))
	if r.x.ResponseRoot != "" {
		fmt.Fprintf(&b, "- x-web response root: `%s`\n", r.x.ResponseRoot)
	}
	if r.spec.LegacyRoot != "" {
		fmt.Fprintf(&b, "- legacy response root: `data.%s`\n", r.spec.LegacyRoot)
	}
	if r.spec.Note != "" {
		fmt.Fprintf(&b, "- note: %s\n", r.spec.Note)
	}
	return b.String()
}

func listOrNone(ss []string) string {
	if len(ss) == 0 {
		return "none"
	}
	return strings.Join(codeAll(ss), ", ")
}

// providerRange returns the min and max provided-variable counts over rows with
// an x-web artifact.
func providerRange(rows []row) (lo, hi int) {
	first := true
	for _, r := range rows {
		if r.x == nil {
			continue
		}
		n := len(r.x.Providers)
		if first || n < lo {
			lo = n
		}
		if first || n > hi {
			hi = n
		}
		first = false
	}
	return lo, hi
}
